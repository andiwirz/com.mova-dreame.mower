test('return reissues OPEN even when displayed and sensor already OPEN, then waits full travel time', async () => {
  const e = fixture();
  let sent = 0, derived = false;
  e.doorState = () => 'open';
  e._lastSensorContactState = 'open';
  e._lastSensorContactAt = Date.now() - 1000;
  e.sensorEnabled = () => true;
  e._doorOpenDurationSeconds = () => 0;
  e._doorOpenReleaseVerified = () => true;
  e.requestOpen = async () => { sent++; return true; };
  e.setDoorState = async (_state, options) => { derived = options.derived; };
  const begun = Date.now();
  assert.equal(await e.ensureDoorOpen('return_from_maintenance', { reassertDisplayedOpen: true }), true);
  assert.equal(sent, 1);
  assert.equal(derived, true);
  assert.ok(Date.now() - begun >= 900);
});
