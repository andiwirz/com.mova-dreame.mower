'use strict';
const test = require('node:test');
const assert = require('node:assert/strict');
const Garage = require('../lib/garage/GarageSafetyEngine');
function fixture() {
  const e = Object.create(Garage.prototype);
  e._commandToken = 8;
  e._returnContext = 'IDLE';
  e._manualGateStopped = false;
  e.device = { getSetting: () => null, _nativeMowerStatus: 'idle', getCapabilityValue: () => 'idle' };
  e.enabled = () => true;
  e.status = () => 'idle';
  e.isDockedHomeStatus = () => false;
  e.log = () => {};
  e.refreshTileStatus = async () => {};
  e._trigger = () => {};
  return e;
}
test('repeated maintenance button acknowledges arrival without clearing proof or sending a command', async () => {
  const e = fixture();
  e._manualMaintenanceReached = true;
  e._manualMaintenancePhase = 'reached';
  e._manualMaintenanceTransit = false;
  e._isCurrentlyAtKnownMaintenancePoint = async () => true;
  let called = false, triggered = false;
  e._trigger = name => { triggered = name === 'garage_maintenance_point_reached'; };
  assert.equal(await e.maintenanceRequested('button_maintenance', async () => { called = true; }), true);
  assert.equal(called, false);
  assert.equal(triggered, true);
  assert.equal(e._manualMaintenanceReached, true);
});
test('explicit direct return waits for verified door opening before dispatching docking', async () => {
  const e = fixture();
  e._physicalOutsideRecoveryEvidence = () => true;
  e.isHomeStatus = () => false;
  e._setLineState = () => {};
  e._setReturnContext = value => { e._returnContext = value; };
  e._lockReturnMaintenancePoint = async () => {};
  e._establishMaintenanceReturnReleaseFromCurrentPosition = async () => null;
  e._decideReturnPath = async () => ({ mode: 'direct' });
  e.markers = { dangerState: async () => ({ inside: false }) };
  e.sensorEnabled = () => false;
  let open, docked = false, gateReady = false;
  e.ensureDoorOpen = () => new Promise(resolve => { open = () => { gateReady = true; resolve(true); }; });
  e._doorOpenReleaseVerified = () => gateReady;
  const pending = e.returnRequested('button_dock', async () => { docked = true; return true; });
  for (let n = 0; n < 20 && !open; n++) await new Promise(resolve => setImmediate(resolve));
  assert.equal(typeof open, 'function');
  assert.equal(docked, false);
  open();
  assert.equal(await pending, true);
  assert.equal(docked, true);
});
